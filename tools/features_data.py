def mv(id, name, type, power, acc, pp, effect=None, target='normal', contact=False, priority=0,
       chance=0, desc='', **extra):
    m = {
        'id': id, 'name': name, 'type': type, 'power': power, 'acc': acc, 'pp': pp,
        'priority': priority, 'target': target, 'contact': contact,
        'protectable': target not in ('self', 'userSide', 'field', 'ally'),
        'effect': effect or {'kind': 'hit'}, 'desc': desc,
    }
    if chance:
        m['chance'] = chance
    m.update(extra)
    return m


def stat(who, **stages):
    return {'kind': 'stat', 'who': who, 'stages': stages}


def status(s):
    return {'kind': 'status', 'status': s}


